<#
Simulacion Wokwi del firmware real (solo simulacion, nunca operacion).

Acciones:
  lint        Revisa diagram.json sin conexion (igual que CI).
  build       Compila el perfil de red de simulacion en build/wokwi-network.
  boot-ntp    Arranque, NTP virtual y primera muestra del sensor.
  reset       Reinicio por software con NVS y checkpoint RTC.
  edge-down   Edge apagado: el firmware reintenta y entrega cuando Edge vuelve.
  edge-link   Enlace ESP32 virtual -> Edge local; Edge guarda la lectura.

Requisitos: Setup-Tools.ps1 ejecutado, wokwi-cli v0.29.1 y WOKWI_CLI_TOKEN en el
entorno (no se imprime). edge-down y edge-link ademas necesitan Edge local y la
pasarela privada de Wokwi (ver docs/simulacion-wokwi.md).
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [ValidateSet('lint', 'build', 'boot-ntp', 'reset', 'edge-down', 'edge-link')]
    [string]$Action,
    [string]$ToolsRoot = $(if ($env:MACHINEGUARD_EMBEDDED_TOOLS) { $env:MACHINEGUARD_EMBEDDED_TOOLS } else { Join-Path $env:LOCALAPPDATA 'MachineGuard\embedded-tools' }),
    [string]$WokwiCli = $(if ($env:WOKWI_CLI_PATH) { $env:WOKWI_CLI_PATH } else { Join-Path $env:USERPROFILE '.wokwi\bin\wokwi-cli.exe' }),
    [string]$EdgeRepo = (Join-Path $PSScriptRoot '..\..\machineguard-edge-api'),
    [int]$EdgePort = 5000,
    [int]$TimeoutMs = 600000
)

$ErrorActionPreference = 'Stop'
$project = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$simDir = Join-Path $project 'simulation\wokwi-network'
$diagram = Join-Path $project 'diagram.json'
$firmware = Join-Path $project 'firmware\MachineGuardNode'
$buildDir = Join-Path $project 'build\wokwi-network'
$stateDir = Join-Path $project 'build\wokwi-sim'
$logDir = Join-Path $stateDir 'logs'
$include = Join-Path $stateDir 'include'
$cli = Join-Path $ToolsRoot 'cli\arduino-cli.exe'
$arduinoConfig = Join-Path $ToolsRoot 'arduino-cli.yaml'
$script:EdgeProcess = $null
$script:AdminKey = $null

function New-Base64UrlSecret([int]$Bytes) {
    $buffer = New-Object byte[] $Bytes
    $random = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $random.GetBytes($buffer) } finally { $random.Dispose() }
    return [Convert]::ToBase64String($buffer).TrimEnd('=').Replace('+', '-').Replace('/', '_')
}

function Test-Token {
    if (-not $env:WOKWI_CLI_TOKEN) {
        $env:WOKWI_CLI_TOKEN = [Environment]::GetEnvironmentVariable('WOKWI_CLI_TOKEN', 'User')
    }
    if (-not $env:WOKWI_CLI_TOKEN) { throw 'WOKWI_CLI_TOKEN is not set in the environment or the user scope.' }
}

function Test-WokwiCli {
    if (-not (Test-Path -LiteralPath $WokwiCli)) { throw "wokwi-cli not found at $WokwiCli. Download v0.29.1 and verify its SHA-256 first." }
}

function Write-SimulationCredentials([string]$Credential) {
    New-Item -ItemType Directory -Path $include -Force | Out-Null
    $content = @(
        '#pragma once',
        '// Generated by scripts/wokwi-sim.ps1. Simulation only. Do not commit or copy outside build/.',
        '#define MG_DEVICE_CODE "ESP32-SIM-01"',
        "#define MG_NODE_CREDENTIAL `"$Credential`""
    ) -join "`n"
    [System.IO.File]::WriteAllText((Join-Path $include 'sim-credentials.h'), $content + "`n", [System.Text.UTF8Encoding]::new($false))
}

function Build-SimulationFirmware {
    if (-not (Test-Path -LiteralPath $cli)) { throw 'Run Setup-Tools.ps1 first.' }
    if (Test-Path -LiteralPath (Join-Path $firmware 'secrets.h')) { throw 'Wokwi network simulation must not include secrets.h.' }
    New-Item -ItemType Directory -Path $buildDir -Force | Out-Null
    $flags = "compiler.cpp.extra_flags=-DMG_WOKWI_NETWORK_PROFILE=1 -I$include"
    & $cli --config-file $arduinoConfig compile --fqbn 'esp32:esp32:esp32doit-devkit-v1' --warnings all `
        --build-path $buildDir --build-property $flags $firmware
    if ($LASTEXITCODE -ne 0) { throw "Simulation build failed with exit code $LASTEXITCODE" }
}

function Start-EdgeForSimulation([switch]$ResetDatabase) {
    if (-not (Test-Path -LiteralPath (Join-Path $EdgeRepo 'edge_api'))) { throw "Edge repository not found at $EdgeRepo." }
    New-Item -ItemType Directory -Path $logDir -Force | Out-Null
    $venv = Join-Path $stateDir 'edge-venv'
    $python = Join-Path $venv 'Scripts\python.exe'
    if (-not (Test-Path -LiteralPath $python)) {
        & python -m venv $venv
        if ($LASTEXITCODE -ne 0) { throw 'Could not create the Edge virtual environment.' }
        & $python -m pip install --quiet --require-hashes -r (Join-Path $EdgeRepo 'requirements.txt')
        if ($LASTEXITCODE -ne 0) { throw 'Could not install the locked Edge runtime.' }
    }
    $database = Join-Path $stateDir 'edge.db'
    if ($ResetDatabase -and (Test-Path -LiteralPath $database)) { Remove-Item -LiteralPath $database -Force }
    if (-not $script:AdminKey) { $script:AdminKey = New-Base64UrlSecret 32 }
    $saved = @{}
    $environment = @{
        EDGE_ADMIN_KEY = $script:AdminKey; EDGE_DATABASE_PATH = $database; EDGE_BIND_HOST = '127.0.0.1'
        EDGE_PORT = "$EdgePort"; EDGE_GATEWAY_ID = 'gateway-wokwi-sim'; MACHINEGUARD_API_URL = ''
        EDGE_DEVICE_CREDENTIAL = ''; EDGE_ADMIN_ALLOWED_IPS = ''
    }
    foreach ($name in $environment.Keys) { $saved[$name] = [Environment]::GetEnvironmentVariable($name, 'Process'); [Environment]::SetEnvironmentVariable($name, $environment[$name], 'Process') }
    try {
        $script:EdgeProcess = Start-Process -FilePath $python -ArgumentList '-m', 'edge_api.server' -WorkingDirectory $EdgeRepo `
            -PassThru -WindowStyle Hidden -RedirectStandardOutput (Join-Path $logDir 'edge.out.log') -RedirectStandardError (Join-Path $logDir 'edge.err.log')
    } finally {
        foreach ($name in $environment.Keys) { [Environment]::SetEnvironmentVariable($name, $saved[$name], 'Process') }
    }
    $headers = @{ 'X-Edge-Admin-Key' = $script:AdminKey }
    for ($attempt = 0; $attempt -lt 60; $attempt++) {
        try {
            Invoke-RestMethod -Uri "http://127.0.0.1:$EdgePort/api/v1/edge/health" -Headers $headers -TimeoutSec 2 | Out-Null
            return
        } catch { Start-Sleep -Seconds 1 }
    }
    Stop-EdgeForSimulation
    throw 'Edge did not become healthy on 127.0.0.1.'
}

function Stop-EdgeForSimulation {
    if ($script:EdgeProcess -and -not $script:EdgeProcess.HasExited) {
        Stop-Process -Id $script:EdgeProcess.Id -Force
        Write-Output "Stopped Edge process $($script:EdgeProcess.Id)."
    }
    $script:EdgeProcess = $null
}

function Register-SimulationNode {
    $headers = @{ 'X-Edge-Admin-Key' = $script:AdminKey }
    $body = @{ deviceCode = 'ESP32-SIM-01'; samplingIntervalSeconds = 10 } | ConvertTo-Json -Compress
    $response = Invoke-RestMethod -Method Post -Uri "http://127.0.0.1:$EdgePort/api/v1/edge/sensor-nodes" -Headers $headers `
        -ContentType 'application/json' -Body $body -TimeoutSec 5
    return [string]$response.nodeCredential
}

function Get-StoredReadingCount {
    $headers = @{ 'X-Edge-Admin-Key' = $script:AdminKey }
    $rows = Invoke-RestMethod -Uri "http://127.0.0.1:$EdgePort/api/v1/edge/readings?limit=500" -Headers $headers -TimeoutSec 5
    return @($rows | Where-Object { $_.deviceCode -eq 'ESP32-SIM-01' }).Count
}

function Invoke-WokwiRun([string]$ScenarioName, [string]$SerialLog, [switch]$Background) {
    Test-WokwiCli
    Test-Token
    New-Item -ItemType Directory -Path $logDir -Force | Out-Null
    $arguments = @('--timeout', "$TimeoutMs", '--diagram-file', $diagram, '--serial-log-file', $SerialLog,
        '--fail-text', 'IDENTITY_STORAGE_ERROR', '--fail-text', 'Guru Meditation')
    if ($ScenarioName) { $arguments += @('--scenario', (Join-Path $simDir $ScenarioName)) }
    $arguments += $simDir
    if ($Background) {
        return Start-Process -FilePath $WokwiCli -ArgumentList $arguments -PassThru -WindowStyle Hidden `
            -RedirectStandardOutput (Join-Path $logDir 'wokwi.out.log') -RedirectStandardError (Join-Path $logDir 'wokwi.err.log')
    }
    & $WokwiCli @arguments | Out-Host
    return $LASTEXITCODE
}

function Wait-SerialText([string]$SerialLog, [string]$Text, [int]$Seconds) {
    for ($i = 0; $i -lt $Seconds; $i++) {
        if ((Test-Path -LiteralPath $SerialLog) -and (Select-String -LiteralPath $SerialLog -SimpleMatch $Text -Quiet)) { return $true }
        Start-Sleep -Seconds 1
    }
    return $false
}

try {
    switch ($Action) {
        'lint' {
            Test-WokwiCli
            & $WokwiCli lint --offline --warnings-as-errors $diagram
            if ($LASTEXITCODE -ne 0) { throw "Lint failed with exit code $LASTEXITCODE" }
        }
        'build' {
            Write-SimulationCredentials ('mgn_' + (New-Base64UrlSecret 32))
            Build-SimulationFirmware
        }
        'boot-ntp' {
            Write-SimulationCredentials (New-Base64UrlSecret 32 | ForEach-Object { "mgn_$_" })
            Build-SimulationFirmware
            $log = Join-Path $logDir 'boot-ntp.serial.log'
            $code = Invoke-WokwiRun -ScenarioName 'boot-ntp.yaml' -SerialLog $log
            Write-Output "Serial log: $log"
            if ($code -ne 0) { throw "boot-ntp scenario failed with exit code $code" }
        }
        'reset' {
            Write-SimulationCredentials (New-Base64UrlSecret 32 | ForEach-Object { "mgn_$_" })
            Build-SimulationFirmware
            $log = Join-Path $logDir 'reset.serial.log'
            $code = Invoke-WokwiRun -ScenarioName 'reset.yaml' -SerialLog $log
            Write-Output "Serial log: $log"
            if ($code -ne 0) { throw "reset scenario failed with exit code $code" }
        }
        'edge-link' {
            Start-EdgeForSimulation -ResetDatabase
            $credential = Register-SimulationNode
            Stop-EdgeForSimulation
            Write-SimulationCredentials $credential
            Build-SimulationFirmware
            Start-EdgeForSimulation
            $log = Join-Path $logDir 'edge-link.serial.log'
            $code = Invoke-WokwiRun -ScenarioName 'boot-ntp.yaml' -SerialLog $log
            if ($code -ne 0) { throw "edge-link run failed with exit code $code" }
            if (-not (Select-String -LiteralPath $log -SimpleMatch 'SIM_EDGE outcome=LocalPending' -Quiet)) { throw 'No LocalPending result in the serial log.' }
            Write-Output "Stored readings for ESP32-SIM-01: $(Get-StoredReadingCount)"
        }
        'edge-down' {
            Start-EdgeForSimulation -ResetDatabase
            $credential = Register-SimulationNode
            Stop-EdgeForSimulation
            Write-SimulationCredentials $credential
            Build-SimulationFirmware
            $log = Join-Path $logDir 'edge-down.serial.log'
            $run = Invoke-WokwiRun -ScenarioName $null -SerialLog $log -Background
            try {
                if (-not (Wait-SerialText $log 'SIM_EDGE outcome=Retry' 240)) { throw 'The firmware did not retry while Edge was down.' }
                Start-EdgeForSimulation
                if (-not (Wait-SerialText $log 'SIM_EDGE outcome=LocalPending' 240)) { throw 'The buffered samples were not delivered after Edge returned.' }
                Write-Output "Stored readings for ESP32-SIM-01: $(Get-StoredReadingCount)"
            } finally {
                if (-not $run.HasExited) { Stop-Process -Id $run.Id -Force }
            }
        }
    }
} finally {
    Stop-EdgeForSimulation
}
